#!/usr/bin/env python3
"""Build resources/languages/ko-KR/pronunciation/stdict_phonemes.tsv.

    python3 -I tools/korean/stdict_phonemes.py --library build/libtts_text_frontend.so \\
        --resources resources --data benchmark/generated/stdict-20260906/data/pronunciations.tsv

Input: the local 표준국어대사전 pronunciation table (headword, ..., pronunciation;
CC BY-SA 2.0 KR, never committed). Each headword is read by the engine's own
rules (pronunciation=hangul with this file empty) and compared with the
dictionary pronunciation after the same colloquial vowel readings (initial 의 으,
other 의 이, ㅖ after a consonant ㅔ, 져 저) and with the length mark removed.
Only the words the rules read differently are written, plus every word ending
in 의 (so a final 의 is not taken for the particle). A headword is skipped when the rules match any
of its entries or variants; otherwise the last variant (허용, the colloquial one) is kept.
"""
import argparse
import collections
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools/web"))
from native import Engine  # noqa: E402

HANGUL = re.compile(r"^[가-힣]+$")
HEADER = """# Generated by tools/korean/stdict_phonemes.py; do not edit by hand.
# Source: 국립국어원 표준국어대사전 (https://stdict.korean.go.kr), CC BY-SA 2.0 KR.
# This file is licensed under CC BY-SA 2.0 KR (STDICT-LICENSE.txt), separately from
# the other resources. Pronunciations the rules miss, and words ending in 의.
"""


def syllables(text):
    for ch in text:
        cp = ord(ch) - 0xAC00
        yield cp // 588, cp % 588 // 28, cp % 28


def compose(o, v, c):
    return chr(0xAC00 + (o * 21 + v) * 28 + c)


def colloquial(word):
    """The vowel readings korean_phoneme.c applies (vowels_before/after)."""
    out = []
    for i, (o, v, c) in enumerate(syllables(word)):
        if v == 19:
            v = (18 if i == 0 else 20) if o == 11 else 20
        elif v == 7 and o != 11:
            v = 5
        if o in (12, 13, 14):
            v = {2: 0, 3: 1, 6: 4, 7: 5, 12: 8, 17: 13}.get(v, v)
        out.append(compose(o, v, c))
    return "".join(out)


def pick(word, variants):
    for v in reversed(variants):
        if not any(w[1] == 11 and r[1] == 15 for w, r in zip(syllables(word), syllables(v))):
            return v
    return variants[0]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--library", required=True)
    ap.add_argument("--resources", required=True)
    ap.add_argument("--data", required=True)
    ap.add_argument("--out", default=str(ROOT / "resources/languages/ko-KR/pronunciation/stdict_phonemes.tsv"))
    args = ap.parse_args()
    entries = collections.defaultdict(list)
    verbs, nouns = set(), set()
    for line in Path(args.data).read_text(encoding="utf-8").splitlines()[1:]:
        f = line.split("\t")
        if len(f) < 5:
            continue
        word = f[0].replace("-", "").replace("^", "")
        if HANGUL.match(word) and ("동사" in f[3] or "형용사" in f[3]) and word.endswith("다") and len(word) >= 2:
            verbs.add(word[:-1])
        if HANGUL.match(word) and "명사" in f[3]:
            nouns.add(word)
        variants = [colloquial(v.replace("ː", "")) for v in f[4].split("|")
                    if HANGUL.match(v.replace("ː", "") or "-") and len(v.replace("ː", "")) == len(word)]
        if HANGUL.match(word) and variants:
            entries[word].append(variants)
    # The rules are measured without the dictionary: empty the file first.
    Path(args.out).write_text(HEADER, encoding="utf-8")
    engine = Engine(Path(args.library), Path(args.resources),
                    dict(default_language="ko-KR", output_mode="speech", pronunciation="hangul"))
    rows, same, differ = [], 0, 0
    # Only a ㄴ coda comes from an ㄹ stem (알다 + ㄴ다 안다); ㅁ stems are never ambiguous.
    ambiguous = {stem for stem in verbs if (ord(stem[-1]) - 0xAC00) % 28 == 4 and
                 stem[:-1] + chr(ord(stem[-1]) - (ord(stem[-1]) - 0xAC00) % 28 + 8) in verbs}
    try:
        for word in sorted(entries):
            rule = engine.normalize(word.encode())["text"]
            prons = [v for variants in entries[word] for v in variants]
            if rule in prons:
                same += 1
                if word.endswith("의"):
                    rows.append((word, rule))
                continue
            if word.endswith("다") and word[:-1] in ambiguous:
                continue
            differ += 1
            # Colloquial: the last variant (허용: 맛있다 마싣따) of the most common entry, but
            # not one that only reads ㅚ as ㅞ (회의 회이, not 훼이): ㅚ stays ㅚ everywhere.
            rows.append((word, collections.Counter(pick(word, v) for v in entries[word]).most_common(1)[0][0]))
    finally:
        engine.close()
    # Phase 2: verb stems in ㄴ or ㅁ (2 when the ㄹ stem of the same shape exists:
    # 안- and 알-), and nouns spelled like such a stem with an ending (남자, 참고).
    rules_file = Path(args.resources) / "languages/ko-KR/rules/phoneme.tsv"
    endings = [l.split("\t")[2] for l in rules_file.read_text(encoding="utf-8").splitlines()
               if l.startswith("phoneme_ending\t")]
    stems = []
    for stem in sorted(verbs):
        coda = (ord(stem[-1]) - 0xAC00) % 28
        if coda not in (4, 16):
            continue
        rieul = stem[:-1] + chr(ord(stem[-1]) - coda + 8)
        stems.append((stem, "2" if coda == 4 and rieul in verbs else "1"))
    blocked = sorted({stem + ending for stem, _ in stems for ending in endings if stem + ending in nouns})
    text = HEADER + "".join("phoneme_word\tko-KR\t%s\t%s\n" % r for r in rows)
    text += "".join("phoneme_stem\tko-KR\t%s\t%s\n" % r for r in stems)
    text += "".join("phoneme_noun\tko-KR\t%s\t1\n" % w for w in blocked)
    Path(args.out).write_text(text, encoding="utf-8")
    print("stems %d, same-spelling nouns %d" % (len(stems), len(blocked)))
    print("words %d, rules agree %d (%.1f%%), exceptions %d, rows %d"
          % (len(entries), same, 100 * same / max(1, len(entries)), differ, len(rows)))


if __name__ == "__main__":
    main()
