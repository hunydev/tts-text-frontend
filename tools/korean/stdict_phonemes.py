#!/usr/bin/env python3
"""Build resources/languages/ko-KR/pronunciation/stdict_phonemes.tsv.

    python3 -I tools/korean/stdict_phonemes.py --library build/libtts_text_frontend.so \\
        --resources resources --data benchmark/generated/stdict-20260906/data/pronunciations.tsv \\
        --archive benchmark/generated/stdict-20260906/stdict.zip

Input: the local 표준국어대사전 pronunciation table (headword, ..., pronunciation;
CC BY-SA 2.0 KR, never committed). Each headword is read by the engine's own
rules (pronunciation=hangul with this file empty) and compared with the
dictionary pronunciation after the same colloquial vowel readings (initial 의 으,
other 의 이, ㅖ after a consonant ㅔ, 져 저) and with the length mark removed.
Only the words the rules read differently are written, plus every word ending
in 의 (so a final 의 is not taken for the particle). A headword is skipped when the rules match any
of its entries or variants; otherwise the last variant (허용, the colloquial one) is kept.
Homographs (2026-10-10): when the rules match only a rare entry, the main entry is kept
instead (건수: 件數 건쑤, not 虔修 건수). The main entry is the one with clearly more usage
examples in the dictionary (--archive, the JSON dump): at least 2, twice as many, and 2 more.
"""
import argparse
import collections
import json
import re
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools/web"))
from native import Engine  # noqa: E402

HANGUL = re.compile(r"^[가-힣]+$")
# Same-spelling words, measured on 1,963 uses in local corpora (2026-10-10, native review).
# Homographs whose main entry is not clear enough to override the rules: both readings are
# common (잠자리 dragonfly / 잠짜리 bed, 산발 散髮 / 山발, 진기 珍奇 / 津氣).
RULE_HOMOGRAPHS = {"잠자리", "산발", "진기"}
# Homographs whose examples do not decide them, read like the everyday sense: native review
# of the ones used at least 3 times in local corpora (2026-10-10). Each reading must be one
# of the dictionary's (after the colloquial vowels).
MAIN_READINGS = {
    "가정집": "가정찝", "개수": "개쑤", "건설사": "건설싸", "권수": "권쑤", "내과": "내꽈", "노인성": "노인썽",
    "단가": "단까", "대권": "대꿘", "대수": "대쑤", "볼거리": "볼꺼리", "비법": "비뻡", "사증": "사쯩",
    "산과": "산꽈", "상과": "상꽈", "송장": "송짱", "승수": "승쑤", "실사": "실싸", "약사법": "약싸뻡",
    "외과": "외꽈", "운송장": "운송짱", "운전대": "운전때", "유가": "유까", "의과": "으꽈", "장미과": "장미꽈",
    "장염": "장념", "전과": "전꽈", "진가": "진까", "철자": "철짜", "타점": "타쩜", "태권": "태꿘",
    "한자": "한짜",
}
# Sino numeral syllables: a word made only of them is also a number read aloud (12 일이,
# 01 공일), so its homograph entries (一二 일리) are not used.
NUMERAL = set("영공일이삼사오육칠팔구십백천만억조")
# A verb form far more often than the noun: read as the verb (목표로 삼고 삼꼬).
VERB_FORMS = {"감고", "검고", "남고", "남지", "담고", "담자", "담지", "더듬자", "삼고", "삼다", "삼지", "삼자",
              "심고", "안고", "참자", "참지", "품고", "품지"}
# A noun far more often than the verb: no object or auxiliary cue (문자 메시지, 남자 있어?).
NOUN_ONLY = {"감소", "감자", "감지", "검소", "남소", "남자", "논고", "논다니", "논소", "논자", "논지", "담소", "문고",
             "문자", "문지", "신고서", "신고자", "신자", "참고서", "참소"}
HEADER = """# Generated by tools/korean/stdict_phonemes.py; do not edit by hand.
# Source: 국립국어원 표준국어대사전 (https://stdict.korean.go.kr), CC BY-SA 2.0 KR.
# This file is licensed under CC BY-SA 2.0 KR (STDICT-LICENSE.txt), separately from
# the other resources. Pronunciations the rules miss, and words ending in 의.
"""


def syllables(text):
    for ch in text:
        cp = ord(ch) - 0xAC00
        yield cp // 588, cp % 588 // 28, cp % 28


def compose(o, v, c):
    return chr(0xAC00 + (o * 21 + v) * 28 + c)


def colloquial(word):
    """The vowel readings korean_phoneme.c applies (vowels_before/after)."""
    out = []
    for i, (o, v, c) in enumerate(syllables(word)):
        if v == 19:
            v = (18 if i == 0 else 20) if o == 11 else 20
        elif v == 7 and o != 11:
            v = 5
        if o in (12, 13, 14):
            v = {2: 0, 3: 1, 6: 4, 7: 5, 12: 8, 17: 13}.get(v, v)
        out.append(compose(o, v, c))
    return "".join(out)


def pick(word, variants):
    for v in reversed(variants):
        if not any(w[1] == 11 and r[1] == 15 for w, r in zip(syllables(word), syllables(v))):
            return v
    return variants[0]


def examples(archive):
    """Usage examples per entry (target_code) in the dictionary JSON dump."""
    out = {}
    with zipfile.ZipFile(archive) as z:
        for name in z.namelist():
            if name.endswith(".json"):
                for item in json.loads(z.read(name))["channel"]["item"]:
                    out[item["target_code"]] = sum(
                        len(s.get("example_info") or []) for p in item["word_info"]["pos_info"]
                        for c in p["comm_pattern_info"] for s in c["sense_info"] if s.get("type") == "일반어")
    return out


def main_entry(rule, entries):
    """The variants of the entry the rules miss when it clearly outnumbers the ones they match."""
    matched = max((n for v, n in entries if rule in v), default=0)
    missed = [(n, v) for v, n in entries if rule not in v]
    if not missed:
        return None
    n, v = max(missed, key=lambda x: x[0])
    return v if n >= 2 and n >= 2 * matched and n - matched >= 2 else None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--library", required=True)
    ap.add_argument("--resources", required=True)
    ap.add_argument("--data", required=True)
    ap.add_argument("--archive", required=True, help="표준국어대사전 JSON dump (stdict.zip), for usage examples")
    ap.add_argument("--out", default=str(ROOT / "resources/languages/ko-KR/pronunciation/stdict_phonemes.tsv"))
    args = ap.parse_args()
    entries = collections.defaultdict(list)
    usage = examples(args.archive)
    verbs, nouns = set(), set()
    for line in Path(args.data).read_text(encoding="utf-8").splitlines()[1:]:
        f = line.split("\t")
        if len(f) < 5:
            continue
        word = f[0].replace("-", "").replace("^", "")
        if HANGUL.match(word) and ("동사" in f[3] or "형용사" in f[3]) and word.endswith("다") and len(word) >= 2:
            verbs.add(word[:-1])
        if HANGUL.match(word) and "명사" in f[3]:
            nouns.add(word)
        variants = [colloquial(v.replace("ː", "")) for v in f[4].split("|")
                    if HANGUL.match(v.replace("ː", "") or "-") and len(v.replace("ː", "")) == len(word)]
        if HANGUL.match(word) and variants:
            entries[word].append((variants, usage.get(int(f[5]), 0) if len(f) > 5 and f[5].isdigit() else 0))
    # The rules are measured without the dictionary: empty the file first.
    Path(args.out).write_text(HEADER, encoding="utf-8")
    engine = Engine(Path(args.library), Path(args.resources),
                    dict(default_language="ko-KR", output_mode="speech", pronunciation="hangul"))
    rows, same, differ, homographs = [], 0, 0, 0
    rules_reading = {}
    # Only a ㄴ coda comes from an ㄹ stem (알다 + ㄴ다 안다); ㅁ stems are never ambiguous.
    ambiguous = {stem for stem in verbs if (ord(stem[-1]) - 0xAC00) % 28 == 4 and
                 stem[:-1] + chr(ord(stem[-1]) - (ord(stem[-1]) - 0xAC00) % 28 + 8) in verbs}
    try:
        for word in sorted(entries):
            rule = engine.normalize(word.encode())["text"]
            rules_reading[word] = rule
            prons = [v for variants, _ in entries[word] for v in variants]
            main = (main_entry(rule, entries[word])
                    if word not in RULE_HOMOGRAPHS and not set(word) <= NUMERAL else None)
            if word in MAIN_READINGS:
                readings = {pick(word, v) for v, _ in entries[word]}
                assert MAIN_READINGS[word] in readings, (word, readings)
                homographs += 1
                rows.append((word, MAIN_READINGS[word]))
                continue
            if rule in prons and main:
                homographs += 1
                rows.append((word, pick(word, main)))
                continue
            if rule in prons:
                same += 1
                if word.endswith("의"):
                    rows.append((word, rule))
                continue
            if word.endswith("다") and word[:-1] in ambiguous:
                continue
            differ += 1
            # Colloquial: the last variant (허용: 맛있다 마싣따) of the most common entry, but
            # not one that only reads ㅚ as ㅞ (회의 회이, not 훼이): ㅚ stays ㅚ everywhere.
            rows.append((word, collections.Counter(pick(word, v) for v, _ in entries[word]).most_common(1)[0][0]))
    finally:
        engine.close()
    # Phase 2: verb stems in ㄴ or ㅁ (2 when the ㄹ stem of the same shape exists:
    # 안- and 알-), and nouns spelled like such a stem with an ending (남자, 참고).
    rules_file = Path(args.resources) / "languages/ko-KR/rules/phoneme.tsv"
    endings = [l.split("\t")[2] for l in rules_file.read_text(encoding="utf-8").splitlines()
               if l.startswith("phoneme_ending\t")]
    stems = []
    for stem in sorted(verbs):
        coda = (ord(stem[-1]) - 0xAC00) % 28
        if coda not in (4, 16):
            continue
        rieul = stem[:-1] + chr(ord(stem[-1]) - coda + 8)
        stems.append((stem, "2" if coda == 4 and rieul in verbs else "1"))
    blocked = sorted({stem + ending for stem, _ in stems for ending in endings if stem + ending in nouns}
                     - VERB_FORMS)
    text = HEADER + "".join("phoneme_word\tko-KR\t%s\t%s\n" % r for r in rows)
    text += "".join("phoneme_stem\tko-KR\t%s\t%s\n" % r for r in stems)
    text += "".join("phoneme_noun\tko-KR\t%s\t%s\n" % (w, "2" if w in NOUN_ONLY else "1") for w in blocked)
    Path(args.out).write_text(text, encoding="utf-8")
    # Self-check (2026-10-10): with the file in place a compound reading may take a listed
    # word inside another headword (화점 in 백화점, 산기 in 계산기), alone or at the end of a
    # compound (롯데백화점). Such a headword is written with its own reading.
    guards = []
    listed = {w for w, _ in rows}
    for _ in range(2):
        engine = Engine(Path(args.library), Path(args.resources),
                        dict(default_language="ko-KR", output_mode="speech", pronunciation="hangul"))
        try:
            added = []
            for word in sorted(entries):
                if word in listed or len(word) < 3 or rules_reading.get(word) is None:
                    continue
                prons = {v for variants, _ in entries[word] for v in variants}
                if rules_reading[word] not in prons:
                    continue
                # Alone, and as the end of a compound (가나 has no coda, so it changes nothing).
                if ((len(word) >= 4 and engine.normalize(word.encode())["text"] not in prons) or
                        engine.normalize(("가나" + word).encode())["text"] != "가나" + rules_reading[word]):
                    added.append((word, rules_reading[word]))
        finally:
            engine.close()
        if not added:
            break
        guards += added
        listed.update(w for w, _ in added)
        text += "".join("phoneme_word\tko-KR\t%s\t%s\n" % r for r in added)
        Path(args.out).write_text(text, encoding="utf-8")
    print("compound guards %d" % len(guards))
    print("stems %d, same-spelling nouns %d" % (len(stems), len(blocked)))
    print("words %d, rules agree %d (%.1f%%), exceptions %d, homograph main entries %d, rows %d"
          % (len(entries), same, 100 * same / max(1, len(entries)), differ, homographs, len(rows)))


if __name__ == "__main__":
    main()
