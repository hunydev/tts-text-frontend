"""Write src/semantic/text_ranges.h: the code points unreadable=drop and read keep as text.

Speech output sends a character no rule could read to the unreadable policy. Under drop
and read that removed whole Thai and Arabic sentences, fullwidth letters and the
punctuation of every script (2026-11-03). Letters, marks, numbers (³) and punctuation are
text, not symbols, so those policies keep them; format characters and variation selectors are
removed without the space a removed symbol leaves. The table comes from Python's
unicodedata (its Unicode version is written into the header):

  python3 tools/unicode_fallback/text_ranges.py src/semantic/text_ranges.h
"""
import sys
import unicodedata
from pathlib import Path


def ranges(pred):
    out, start = [], None
    for cp in range(0x110000):
        if pred(cp):
            if start is None:
                start = cp
        elif start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def selector(cp):
    return 0xFE00 <= cp <= 0xFE0F or 0xE0100 <= cp <= 0xE01EF


def table(name, rows):
    body = ",\n".join("    {0x%05X, 0x%05X}" % r for r in rows)
    return "static const uint32_t %s[][2] = {\n%s\n};\n" % (name, body)


def main():
    out = Path(sys.argv[1])
    text = ranges(lambda cp: unicodedata.category(chr(cp))[0] in "LMNP" and not selector(cp))
    silent = ranges(lambda cp: unicodedata.category(chr(cp)) == "Cf" or selector(cp))
    out.write_text(
        "/* Generated by tools/unicode_fallback/text_ranges.py from Unicode %s (Python\n"
        "   unicodedata). Letters, marks, numbers and punctuation that unreadable=drop and read\n"
        "   keep as text; format characters and variation selectors those policies remove\n"
        "   silently.\n"
        "   Do not edit by hand. */\n"
        "#ifndef TTF_TEXT_RANGES_H\n#define TTF_TEXT_RANGES_H\n#include <stdint.h>\n"
        % unicodedata.unidata_version
        + table("ttf_text_characters", text) + table("ttf_silent_characters", silent)
        + "#endif\n", encoding="utf-8", newline="\n")
    print("%d text ranges, %d silent ranges -> %s" % (len(text), len(silent), out))


if __name__ == "__main__":
    main()
