#!/usr/bin/env python3
"""Generate the speech readings of styled Latin letters (mathematical alphanumerics).

    python3 tools/unicode_fallback/math_letters.py

Styled text writes words with the Mathematical Alphanumeric Symbols block (𝐀𝐁𝐂 bold,
𝘈 italic, 𝔸 double-struck, 𝒜 script, 𝖠 sans-serif, 𝙰 monospace …) and the letterlike
symbols that stand in its gaps (ℎ ℂ ℝ ℬ …). Each letter whose compatibility form (NFKC) is
one ASCII letter reads like the full-width letter of the same name in speech-characters.tsv:
the Korean letter name (𝐀 에이), and in English the letter itself (𝐀 A). Greek letters and
digits are not here (the digits read as numbers in the numeric scanner view).
"""
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RULES = str(ROOT / "resources/languages/{}/rules")
HEADER = """# Generated by tools/unicode_fallback/math_letters.py; do not edit by hand.
# Styled Latin letters (Mathematical Alphanumeric Symbols U+1D400-U+1D6A3 and the letterlike
# symbols in its gaps) read like the full-width letter of the same name (2026-10-26).
"""


def styled_letters():
    # the letterlike symbols that fill the block's gaps (ℎ, ℂ, ℝ, ℬ …); not ℓ, K (Kelvin) or ℹ,
    # which are units and signs
    gaps = [0x2102, 0x210A, 0x210B, 0x210C, 0x210D, 0x210E, 0x2110, 0x2111, 0x2112, 0x2115, 0x2119,
            0x211A, 0x211B, 0x211C, 0x211D, 0x2124, 0x2128, 0x212C, 0x212D, 0x212F, 0x2130, 0x2131,
            0x2133, 0x2134]
    cps = list(range(0x1D400, 0x1D6A4)) + gaps
    for cp in cps:
        ch = chr(cp)
        try:
            unicodedata.name(ch)
        except ValueError:
            continue
        folded = unicodedata.normalize("NFKC", ch)
        if len(folded) == 1 and folded.isascii() and folded.isalpha():
            yield ch, folded


def main():
    for lang in ("ko-KR", "en-US"):
        base = {}
        for line in (Path(RULES.format(lang)) / "speech-characters.tsv").read_text(encoding="utf-8").splitlines():
            parts = line.split("\t")
            if len(parts) == 4 and parts[0] == "speech_character":
                ascii_letter = unicodedata.normalize("NFKC", parts[2])
                base[ascii_letter] = parts[3]
        rows = [f"speech_character\t{lang}\t{ch}\t{base[letter]}\n" for ch, letter in styled_letters()
                if letter in base]
        out = Path(RULES.format(lang)) / "speech-math-letters.tsv"
        out.write_text(HEADER + "".join(rows), encoding="utf-8", newline="\n")
        print(lang, len(rows), "rows")


if __name__ == "__main__":
    main()
