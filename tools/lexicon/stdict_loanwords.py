#!/usr/bin/env python3
"""Build the Korean loanword lexicon from the 표준국어대사전 (국립국어원).

    stdict_loanwords.py STDICT.zip OUT.tsv [--report]

Build time only; the dictionary dump is not stored in the repository. The output
is licensed CC BY-SA 2.0 KR like its source (STDICT-LICENSE.txt in the same
directory), separately from the rest of the resources.

Selection
    * 외래어 words (단어) with one Latin original of three or more lowercase
      letters; the Hangul headword is the reading (ballet 발레, ambulance 앰뷸런스).
    * Entries whose every sense only points to another word (→ 코미디) are
      non-standard variants and are skipped.
    * One spelling with several readings keeps the English one when the others
      come from other languages (mark 마크, not the German 마르크); otherwise it
      is ambiguous and left out (bass 베이스/배스).
    * Spellings already in a project lexicon keep the project reading, and common
      English function words are never entries.
    * An all-capital surface (CAT, PET) is an initialism, not the loanword: the
      engine never applies a loanword row to it (no lexicon_case rows needed).
    * Rows are kind loanword, not lexicon: the engine reads a word with them only
      when no declared reading exists, and they never make a word "declared"
      (ham7239 keeps its letters; SAVE20 세이브 트웬티 needs a project entry).
"""
import collections
import json
import re
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
HEADER = """# Generated by tools/lexicon/stdict_loanwords.py; do not edit by hand.
# Source: 국립국어원 표준국어대사전 (https://stdict.korean.go.kr), CC BY-SA 2.0 KR.
# This file is licensed under CC BY-SA 2.0 KR (STDICT-LICENSE.txt), separately from
# the other resources. Standard Korean spellings of loanwords, keyed by the original
# Latin spelling; project lexicons win over it.
"""
STOP = set("""the and for are but not you all any can her was one our out day get has him his how its may new now
old see two way who boy did let put say she too use from have into just like more most much must only over such
than that them then they this very what when will with your about after again also back been before being both
down each even here just made make many most never other over said same some still take these those through under
upon well were where which while would yes off yet set ever per via via""".split())
# Spellings whose dictionary form is not the one Korean text uses: net 네트 (넷제로, 닷넷).
EXCLUDE = {"net"}


def headword(word):
    return re.sub(r"\d+$", "", word).replace("-", "")


def entries(archive):
    with zipfile.ZipFile(archive) as z:
        for name in sorted(z.namelist()):
            if not name.endswith(".json"):
                continue
            for item in json.loads(z.read(name))["channel"]["item"]:
                w = item["word_info"]
                ol = w.get("original_language_info") or []
                if w["word_unit"] != "단어" or w["word_type"] != "외래어" or len(ol) != 1:
                    continue
                src = ol[0].get("original_language", "").strip()
                reading = headword(w["word"])
                if not re.fullmatch(r"[a-z]{3,}", src) or not re.fullmatch(r"[가-힣]+", reading):
                    continue
                senses = [s for p in w["pos_info"] for c in p["comm_pattern_info"] for s in c["sense_info"]]
                if senses and all(s["definition"].lstrip().startswith("→") for s in senses):
                    continue
                yield src, reading, ol[0]["language_type"]


def existing_keys():
    keys = set()
    for path in (ROOT / "resources").rglob("*.tsv"):
        if path.name == "stdict_loanwords.tsv":
            continue
        for line in path.open(encoding="utf-8"):
            if line.startswith("lexicon\tko-KR\ten-US:"):
                keys.add(line.split("\t")[2][6:])
    return keys


def build(archive):
    by = collections.defaultdict(lambda: collections.defaultdict(set))
    for src, reading, lang in entries(archive):
        by[src][lang].add(reading)
    have = existing_keys()
    table, skipped = {}, collections.Counter()
    for src, langs in by.items():
        if src in STOP or src in EXCLUDE:
            skipped["function word"] += 1
            continue
        if src in have:
            skipped["project lexicon"] += 1
            continue
        readings = langs.get("영어") or set().union(*langs.values())
        if len(readings) != 1:
            skipped["ambiguous"] += 1
            continue
        table[src] = next(iter(readings))
    return table, skipped


def main():
    table, skipped = build(sys.argv[1])
    rows = ["loanword\tko-KR\ten-US:%s\t%s\n" % (k, table[k]) for k in sorted(table)]
    Path(sys.argv[2]).write_text(HEADER + "".join(rows), encoding="utf-8", newline="\n")
    print("%d loanwords; skipped %s" % (len(table), dict(skipped)))


if __name__ == "__main__":
    main()
