#!/usr/bin/env python3
"""Build hanja_readings_variants.tsv: Korean readings for simplified Chinese and
Japanese new-form characters, taken from the traditional form's row in
hanja_readings.tsv (Unihan, Unicode License). A variant that already has a
reading in any hanja reading table keeps it. Pairs are hand-authored in
data/cjk/hanja_variants_source.txt; a line `char<TAB>=reading` gives a project
reading for a character Unihan has no Korean reading for (你 니). The table also
carries the Unihan kHangul reading of characters outside the K0/K1 repertoire of
hanja_readings.tsv (青 청, 教 교; 2026-10-26).

  python3 -I tools/cjk/variants.py          # write the table
  python3 -I tools/cjk/variants.py --check  # verify it is current
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(Path(__file__).resolve().parent))
import generate  # noqa: E402  (kHangul resolution shared with hanja_readings.tsv)
SOURCE = ROOT / "data/cjk/hanja_variants_source.txt"
CJK = ROOT / "resources/languages/ko-KR/cjk"
OUT = CJK / "hanja_readings_variants.tsv"
HEADER = (
    "# Generated by tools/cjk/variants.py from data/cjk/hanja_variants_source.txt; do not edit.\n"
    "# Readings of simplified Chinese and Japanese new-form characters, each taken from its\n"
    "# traditional form in hanja_readings.tsv (Unihan, Unicode License: UNICODE-LICENSE.txt),\n"
    "# then project readings (`=`) and the Unihan kHangul of characters outside K0/K1.\n"
    "# Loaded with the hanja reading option; used inside a sentence with Hangul, or in every\n"
    "# sentence under matrix=declared (a bare 中国 日本 otherwise keeps its simplified form).\n"
    "# A character with its own reading keeps it.\n"
)


def table(path):
    rows = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("#") or not line.strip():
            continue
        kind, _, key, value = line.split("\t")
        if kind == "hanja_reading":
            rows[key] = value
    return rows


def build():
    unihan = table(CJK / "hanja_readings.tsv")
    have = dict(unihan)
    have.update(table(CJK / "hanja_readings_stdict.tsv"))
    _, readings, _ = generate.load(ROOT / "data/cjk")
    khangul = {}
    for codepoint, entries in readings.items():
        ordered, _ = generate.resolve(entries)
        if ordered:
            khangul[chr(codepoint)] = "|".join(s for s, _ in ordered)
    out, kept, missing, seen = [], [], [], set()
    for line in SOURCE.read_text(encoding="utf-8").splitlines():
        if line.startswith("#") or not line.strip():
            continue
        variant, traditional = line.split("\t")
        if variant in seen:
            continue
        seen.add(variant)
        if variant in have:
            kept.append(variant)
        elif traditional.startswith("="):
            if variant in khangul:      # Unihan has a reading after all: it wins
                missing.append(variant)
            else:
                out.append(f"hanja_variant_reading\tko-KR\t{variant}\t{traditional[1:]}\n")
        elif traditional in unihan or traditional in khangul:
            reading = unihan.get(traditional) or khangul[traditional]
            out.append(f"hanja_variant_reading\tko-KR\t{variant}\t{reading}\n")
        else:
            missing.append(traditional)
    for character in sorted(khangul):
        if character not in have and character not in seen:
            seen.add(character)
            out.append(f"hanja_variant_reading\tko-KR\t{character}\t{khangul[character]}\n")
    return HEADER + "".join(out), len(out), kept, missing


def main():
    text, count, kept, missing = build()
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            raise SystemExit(f"{OUT} is stale; run tools/cjk/variants.py")
        print("ok")
        return
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"{count} rows; kept own reading: {''.join(kept)}; traditional without a reading: {''.join(missing)}")


if __name__ == "__main__":
    main()
