#!/usr/bin/env python3
"""Build hanja_readings_stdict.tsv: readings for Han characters outside the Unihan
table, taken from the Hanja words of the 표준국어대사전 (국립국어원).

    stdict_readings.py STDICT.zip OUT.tsv [--holdout]

Build time only; the dictionary dump is not stored in the repository. The output
is licensed CC BY-SA 2.0 KR like its source (see STDICT-LICENSE.txt next to it),
separately from the rest of the resources.

Method
    * Only words of word_type 한자어 whose original_language is entirely Han and
      whose headword has one Hangul syllable per character are used, so each
      character aligns with exactly one syllable.
    * Characters already in hanja_readings.tsv are skipped: the Unihan table wins.
    * A reading seen in a non-initial position is canonical. Word-initial
      syllables may be 두음법칙 forms, so they count only when a character never
      appears elsewhere.
    * Further readings are kept (preferred first) when seen at least twice and at
      least a quarter as often as the first; ties break by syllable order.
    * A reading that is only the 두음 form of a Unihan kHangul reading becomes that
      reading: 郎 appears inside words as 낭 (목낭청, from the compound 郎廳) but
      reads 랑 (新郎 신랑), and the run-time rule restores 낭 at the start.
    --holdout trains on 4/5 of the words and reports agreement on the rest.
"""
import collections
import hashlib
import json
import re
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TABLE = ROOT / "resources/languages/ko-KR/cjk/hanja_readings.tsv"
UNIHAN = ROOT / "data/cjk/unihan-k-subset.txt"
HAN = re.compile(r"^[㐀-䶿一-鿿豈-﫿\U00020000-\U0003134f]+$")
HEADER = """# Generated by tools/cjk/stdict_readings.py; do not edit by hand.
# Source: 국립국어원 표준국어대사전 (https://stdict.korean.go.kr), CC BY-SA 2.0 KR.
# This file is licensed under CC BY-SA 2.0 KR (STDICT-LICENSE.txt), separately from
# the other resources. Readings for Han characters outside hanja_readings.tsv, taken
# from the dictionary's Hanja words; 두음법칙 forms are applied at run time.
"""


def headword(word):
    return re.sub(r"\d+$", "", word).replace("-", "").replace("^", "")


def words(archive):
    with zipfile.ZipFile(archive) as z:
        for name in sorted(z.namelist()):
            if not name.endswith(".json"):
                continue
            for item in json.loads(z.read(name))["channel"]["item"]:
                w = item["word_info"]
                ol = w.get("original_language_info") or []
                if w["word_unit"] != "단어" or w["word_type"] != "한자어" or not ol:
                    continue
                if any(o["language_type"] != "한자" for o in ol):
                    continue
                source = "".join(o.get("original_language", "") for o in ol)
                hangul = headword(w["word"])
                if HAN.match(source) and len(source) == len(hangul) and re.fullmatch("[가-힣]+", hangul):
                    yield source, hangul


def known():
    have = set()
    for line in TABLE.open(encoding="utf-8"):
        parts = line.rstrip("\n").split("\t")
        if not line.startswith("#") and len(parts) == 4:
            have.add(parts[2])
    return have


def unihan():
    readings = collections.defaultdict(list)
    for line in UNIHAN.open(encoding="utf-8"):
        parts = line.rstrip("\n").split("\t")
        if len(parts) == 3 and parts[1] == "kHangul":
            readings[chr(int(parts[0][2:], 16))] = [r.split(":")[0] for r in parts[2].split()]
    return readings


def build(pairs, have, original=None):
    inner = collections.defaultdict(collections.Counter)
    initial = collections.defaultdict(collections.Counter)
    for source, hangul in pairs:
        for i, (c, s) in enumerate(zip(source, hangul)):
            if c not in have:
                (inner if i else initial)[c][s] += 1
    table = {}
    for c in set(inner) | set(initial):
        counts = inner[c] or initial[c]
        ranked = sorted(counts.items(), key=lambda kv: (-kv[1], kv[0]))
        top = ranked[0][1]
        kept = [s for s, n in ranked if s == ranked[0][0] or (n >= 2 and 4 * n >= top)]
        for i, s in enumerate(kept):
            restored = [r for r in (original or {}).get(c, []) if r != s and as_initial(r) == s]
            if restored and s not in (original or {}).get(c, []):
                kept[i] = restored[0]
        table[c] = list(dict.fromkeys(kept))
    return table


INITIAL = {"랴": "야", "려": "여", "례": "예", "료": "요", "류": "유", "리": "이", "라": "나", "래": "내",
           "로": "노", "뢰": "뇌", "루": "누", "르": "느", "냐": "야", "녀": "여", "뇨": "요", "뉴": "유", "니": "이"}


def as_initial(s):
    base = (ord(s) - 0xAC00) // 28 * 28 + 0xAC00
    form = INITIAL.get(chr(base))
    return chr(ord(form) + (ord(s) - base)) if form else s


def main():
    archive, out = sys.argv[1], Path(sys.argv[2])
    pairs = list(dict.fromkeys(words(archive)))
    have = known()
    if "--holdout" in sys.argv:
        test = [p for p in pairs if hashlib.sha1(p[0].encode()).digest()[0] % 5 == 0]
        train = [p for p in pairs if hashlib.sha1(p[0].encode()).digest()[0] % 5]
        table = build(train, have, unihan())
        seen = right = unseen = 0
        for source, hangul in test:
            for i, (c, s) in enumerate(zip(source, hangul)):
                if c in have:
                    continue
                if c not in table:
                    unseen += 1
                    continue
                seen += 1
                guess = table[c][0] if i else as_initial(table[c][0])
                right += guess == s
        print("holdout: %d characters read, %d agree (%.1f%%), %d not covered by the training words"
              % (seen, right, 100 * right / max(seen, 1), unseen))
        return
    table = build(pairs, have, unihan())
    rows = ["hanja_reading\tko-KR\t%s\t%s\n" % (c, "|".join(table[c])) for c in sorted(table)]
    out.write_text(HEADER + "".join(rows), encoding="utf-8", newline="\n")
    print("%d words, %d characters outside the Unihan table" % (len(pairs), len(rows)))


if __name__ == "__main__":
    main()
