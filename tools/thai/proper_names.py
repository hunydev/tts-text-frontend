#!/usr/bin/env python3
"""Build resources/languages/th-TH/rules/names.tsv (th_name) from the owner's proper-noun list.

  python3 -I tools/thai/proper_names.py [SOURCE]

SOURCE (default benchmark/generated/th-owner/th-real/th_proper_nouns.tsv, local only) has
type<TAB>thai<TAB>wikidata_en<TAB>rtgs<TAB>variants: Wikidata labels (CC0) and royin romanizations
by pythainlp (Apache-2.0). A key is the English label in lowercase without spaces or hyphens (bangrak, somchai); the Thai spelling drops the administrative word before a place
name (อำเภอ, ตำบล, จังหวัด ...), a kind word the key does not carry (silom สีลม, not ถนนสีลม) and its
spaces. A key with several spellings keeps the one most rows
give. Keys the pack already spells as English words (electronic_word) are left out, and so are
keys shorter than four letters or longer than 24, and spellings over 30 characters
(an address label is short).
"""
import collections
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "benchmark/generated/th-owner/th-real/th_proper_nouns.tsv"
OUT = ROOT / "resources/languages/th-TH/rules/names.tsv"
SPEECH = ROOT / "resources/languages/th-TH/rules/speech.tsv"
# the kinds of names an address carries; subdistricts, temples, islands and parks (about half the
# list) are left out, as every row costs engine creation time
TYPES = {"given_name", "family_name", "province", "district", "city", "road", "station", "mall", "company",
         "university", "hospital", "airport"}
PREFIX = ("เทศบาลตำบล", "เทศบาลเมือง", "เทศบาลนคร", "อำเภอ", "ตำบล", "จังหวัด", "เขต", "แขวง", "กิ่งอำเภอ")
LATIN = re.compile(r"^[a-z]{4,24}$")
KIND = {"ถนน": ("road", "thanon"), "สถานี": ("station", "sathani"), "ท่าอากาศยาน": ("airport", "thaakatyan"),
        "มหาวิทยาลัย": ("university", "mahawitthayalai"), "โรงพยาบาล": ("hospital", "rongphayaban"),
        "อุทยานแห่งชาติ": ("park", "utthayan"), "เกาะ": ("ko", "island"), "วัด": ("wat",)}


def key(text):
    return re.sub(r"[\s\-'’.]", "", text.lower())


def main():
    english = {l.split("\t")[2] for l in SPEECH.read_text(encoding="utf-8").splitlines()
               if l.startswith("electronic_word\tth-TH\t")}
    votes = collections.defaultdict(collections.Counter)
    for line in SOURCE.read_text(encoding="utf-8").splitlines():
        if line.startswith("#"):
            continue
        f = line.split("\t")
        if len(f) < 4 or f[0] not in TYPES:
            continue
        thai = f[1]
        for p in PREFIX:
            if thai.startswith(p) and len(thai) > len(p) + 1:
                thai = thai[len(p):]
                break
        thai = re.sub(r"\s+", "", thai)
        if not re.fullmatch(r"[ก-๎]+", thai):
            continue
        en, rtgs = f[2], f[3]
        # Bang Rak District bangrak, Chiang Mai Province chiangmai
        en = re.sub(r"\s+(district|subdistrict|province|municipality)$", "", en, flags=re.I)
        if f[0] in ("district", "subdistrict", "municipality"):
            en = re.sub(r"^(mueang|amphoe|tambon|khet|khwaeng)\s+", "", en, flags=re.I) if len(en.split()) > 1 else en
            rtgs = re.sub(r"^(amphoe|tambon|khet|khwaeng|thesaban(tambon|mueang|nakhon)?)", "", rtgs)
        # the English label as people write it (Sukhumvit, Boonsong), not the royin form; a
        # station, road or building also without its kind word (Chatuchak station chatuchak)
        base = re.sub(r"\s+((mrt|bts|arl|srt)\s+)?(station|road|airport|hospital|university|mall)$", "", en,
                      flags=re.I)
        for k in {key(en), key(base)}:
            if not LATIN.match(k) or k in english:
                continue
            spelled = thai
            # silom สีลม, not ถนนสีลม: a kind word stays only where the key says it (silomroad)
            for word, cues in KIND.items():
                if spelled.startswith(word) and len(spelled) > len(word) + 1 and not any(c in k for c in cues):
                    spelled = spelled[len(word):]
                    break
            if len(spelled) <= 30:
                votes[k][spelled] += 1
    rows = []
    for k in sorted(votes):
        thai = sorted(votes[k].items(), key=lambda kv: (-kv[1], len(kv[0]), kv[0]))[0][0]
        rows.append(f"th_name\tth-TH\t{k}\t{thai}\n")
    OUT.write_text("# Romanized Thai proper names in addresses (bangrak บางรัก, somchai สมชาย): th_name key in\n"
                   "# lowercase without spaces, Thai spelling. Generated by tools/thai/proper_names.py from\n"
                   "# Wikidata labels (CC0) and royin romanizations by pythainlp (Apache-2.0), 2026-10-15.\n"
                   + "".join(rows), encoding="utf-8")
    print(len(rows))


if __name__ == "__main__":
    main()
